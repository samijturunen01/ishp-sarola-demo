/**
 * Rebuilds the authentic Itä-Suomen Huoltopalvelu Sarola nameplate logo as
 * resolution-independent SVG paths.
 *
 * Reference: https://ishp.fi/wp-content/themes/sarola/images/object2028756370.png
 * (228 × 90 px). The original is an ellipse with a thin orange rim, a vertical
 * black → steel → polished-white gradient and three lines of bold Times-style
 * serif in orange with a dark drop shadow. Tinos Bold (Apache-2.0) is metrically
 * compatible with Times New Roman Bold, so converting it to outlines preserves
 * letter shapes, counters and proportions without shipping a font.
 *
 * Measured from the reference (original px): line widths / baselines
 *   "Itä-Suomen"     ≈ 102.5 wide, baseline ≈ 25.8
 *   "Huoltopalvelu"  ≈ 155   wide, baseline ≈ 51.3
 *   "Sarola"         ≈ 52    wide, baseline ≈ 75.8
 *
 * Output: src/components/brand/logoPaths.ts and public/brand/ishp-logo.svg
 * Run: node scripts/build-logo.mjs
 */
import opentype from 'opentype.js'
import fs from 'node:fs/promises'

const SCALE = 4 // work in a 912 × 360 viewBox for clean coordinates
const W = 228 * SCALE
const H = 90 * SCALE
const fontFile = 'node_modules/@fontsource/tinos/files/tinos-latin-700-normal.woff'
const buf = await fs.readFile(fontFile)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))

const lines = [
  { id: 'ita', text: 'Itä-Suomen', width: 102.5, baseline: 25.8 },
  { id: 'huolto', text: 'Huoltopalvelu', width: 155, baseline: 51.3 },
  { id: 'sarola', text: 'Sarola', width: 52, baseline: 75.8 },
]

const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10))

const out = []
for (const line of lines) {
  const probe = font.getAdvanceWidth(line.text, 100)
  const size = (line.width * SCALE * 100) / probe
  const advance = font.getAdvanceWidth(line.text, size)
  const x = W / 2 - advance / 2
  const y = line.baseline * SCALE
  const path = font.getPath(line.text, x, y, size)
  // The reference glyphs render ~6 % shorter than Tinos at equal width
  // (small-size hinting in the original bitmap) – squash around the baseline.
  for (const c of path.commands) {
    for (const k of ['y', 'y1', 'y2']) if (k in c) c[k] = y + (c[k] - y) * 0.94
  }
  const bb = path.getBoundingBox()
  out.push({
    id: line.id,
    text: line.text,
    d: round(path.toPathData(1)),
    box: { x: Math.round(bb.x1), y: Math.round(bb.y1), w: Math.round(bb.x2 - bb.x1), h: Math.round(bb.y2 - bb.y1) },
  })
  console.log(`${line.text}: size ${size.toFixed(1)} → cap-top ${(bb.y1 / SCALE).toFixed(1)}, bottom ${(bb.y2 / SCALE).toFixed(1)}`)
}

const ts = `// Generated by scripts/build-logo.mjs — do not edit by hand.
// Text outlines of the authentic ISHP Sarola nameplate (Tinos Bold ≈ Times Bold).
export const LOGO_VIEWBOX = { w: ${W}, h: ${H} } as const

export const LOGO_ELLIPSE = { cx: ${W / 2}, cy: ${H / 2}, rx: ${W / 2 - 6}, ry: ${H / 2 - 6} } as const

export const LOGO_LINES = ${JSON.stringify(out, null, 2)} as const
`
await fs.mkdir('src/components/brand', { recursive: true })
await fs.writeFile('src/components/brand/logoPaths.ts', ts)

// Static SVG version (used for OG image generation, favicon base, docs).
const e = { cx: W / 2, cy: H / 2, rx: W / 2 - 6, ry: H / 2 - 6 }
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" role="img" aria-labelledby="t">
  <title id="t">Itä-Suomen Huoltopalvelu Sarola</title>
  <defs>
    <linearGradient id="plate" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0.03" stop-color="#000"/>
      <stop offset="0.5" stop-color="#7f7f7f"/>
      <stop offset="0.96" stop-color="#f3f3f3"/>
    </linearGradient>
    <filter id="glow" x="-5%" y="-10%" width="110%" height="120%">
      <feGaussianBlur stdDeviation="3"/>
    </filter>
  </defs>
  <ellipse cx="${e.cx}" cy="${e.cy}" rx="${e.rx}" ry="${e.ry}" fill="none" stroke="#ff7a45" stroke-width="9" opacity=".55" filter="url(#glow)"/>
  <ellipse cx="${e.cx}" cy="${e.cy}" rx="${e.rx}" ry="${e.ry}" fill="url(#plate)" stroke="#ff5a1c" stroke-width="7"/>
  <g transform="translate(5 5)" fill="#1a0a04" opacity=".85">${out.map((l) => `<path d="${l.d}"/>`).join('')}</g>
  <g fill="#ff6429">${out.map((l) => `<path d="${l.d}"/>`).join('')}</g>
</svg>
`
await fs.mkdir('public/brand', { recursive: true })
await fs.writeFile('public/brand/ishp-logo.svg', svg)

// Favicon: a miniature of the nameplate carrying the logo's serif "S".
const sSize = 46
const sAdv = font.getAdvanceWidth('S', sSize)
const sPath = round(font.getPath('S', 32 - sAdv / 2, 48, sSize).toPathData(1))
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <defs><linearGradient id="p" x1="0" y1="0" x2="0" y2="1"><stop offset=".05" stop-color="#000"/><stop offset=".55" stop-color="#7f7f7f"/><stop offset="1" stop-color="#f3f3f3"/></linearGradient></defs>
  <ellipse cx="32" cy="32" rx="30" ry="25" fill="url(#p)" stroke="#ff5a1c" stroke-width="3"/>
  <path d="${sPath}" transform="translate(1.5 1.5)" fill="#1a0a04" opacity=".85"/>
  <path d="${sPath}" fill="#ff6429"/>
</svg>
`
await fs.writeFile('public/brand/favicon.svg', favicon)
console.log('Wrote src/components/brand/logoPaths.ts and public/brand/ishp-logo.svg')
